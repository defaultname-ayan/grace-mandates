"""Rebuild the README '## Results' section from runs/<run>/eval.json.

The numbers in the README must never be hand-typed: they drift the moment the
cohort or the policy changes. Run after `grace eval` (and `grace eval
--on-sample`, whose payload is saved as eval_online_sample.json).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from grace.util import fmt_inr

BEGIN, END = "<!-- results:begin -->", "<!-- results:end -->"


def pct(v):
    return "–" if v is None else f"{v:.1%}"


def table(arms: dict, cols: list[str]) -> str:
    rows = [
        ("Mandates scored", "n_scored", str), ("At risk", "at_risk", str),
        ("**Mandates preserved**", "mandates_preserved", str),
        ("**Rupees preserved**", "rupees_preserved_paise", fmt_inr),
        ("Preservation rate", "preservation_rate", pct), ("Interventions", "interventions", str),
        ("False interventions", "false_interventions", str),
        ("**False-intervention rate**", "false_intervention_rate", pct),
        ("False-intervention cost", "false_intervention_cost_paise", fmt_inr),
        ("Escalation rate", "escalation_rate", pct), ("Cause accuracy", "cause_accuracy", pct),
        ("Action regret (lower is better)", "action_regret", lambda v: "–" if v is None else f"{v:.4f}"),
        ("Intent conversion", "intent_conversion_rate", pct),
    ]
    head = "| Metric | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols)
    body = "\n".join(
        "| " + label + " | " + " | ".join(
            (f(arms[c].get(key)) if arms[c].get(key) is not None else "–") for c in cols) + " |"
        for label, key, f in rows)
    return head + "\n" + body


def build(run_dir: Path) -> str:
    ev = json.loads((run_dir / "eval.json").read_text())
    arms, cmp = ev["arms"], ev["comparison"]
    a, b = arms["agent"], arms["baseline"]
    pred = ev.get("predictor", {})
    out = [BEGIN, "",
           "Holdout only (30% of the cohort, never used for fitting or threshold selection).",
           "**The cohort is synthetic — see [Honesty](#honesty).** Regenerated by "
           "`python -m scripts.update_readme_results`; never hand-edited.", "",
           table(arms, ["noop", "baseline", "agent"]).replace("| noop |", "| do nothing |")
           .replace("| baseline |", "| rules baseline |"), "",
           f"**Net of the harm it causes:** the agent preserves {fmt_inr(cmp['agent']['rupees_preserved_lift_paise'])} "
           f"more than doing nothing and costs {fmt_inr(a['false_intervention_cost_paise'])} in revenue put at "
           f"risk by intervening on {a['false_interventions']} healthy mandates — "
           f"**net {fmt_inr(cmp['agent']['net_rupees_paise'])}**, against the baseline's "
           f"{fmt_inr(cmp['baseline']['net_rupees_paise'])}.", ""]
    fi = a.get("false_intervention_rate") or 0.0
    out += [f"**Read the false-intervention row before the rupee row.** The agent acts more often, and "
            f"{pct(fi)} of its interventions land on mandates that would have paid anyway; the rules "
            f"baseline's rate is {pct(b.get('false_intervention_rate'))}, because it mostly reacts to failures "
            f"that have already happened. That is the real trade: acting earlier sometimes means acting wrongly.", "",
            "**Counterfactual formula.** `rupees preserved = Σ plan_amount × min(3, remaining_cycles)` over "
            "at-risk mandates that survive. Survival is drawn from the cohort's counterfactual table using "
            "**common random numbers** — one fixed uniform per mandate shared across all arms, so arms differ "
            "only by the action they chose, never by luck.", ""]
    sp = run_dir / "eval_online_sample.json"
    if sp.exists():
        s = json.loads(sp.read_text())
        sa, sb = s["arms"]["agent"], s["arms"]["baseline"]
        llm = sa["batch"].get("llm", {})
        size = s.get("sample", {}).get("size") or sa["n_scored"]
        out += [f"### Live model result ({size}-mandate online sample)", "",
                "The table above ran the deterministic offline stub. Below is a **real Gemini run** on a "
                f"deterministic {size}-mandate subset of the holdout, every arm scored on exactly those "
                f"{size} so the comparison stays paired. Reproduce with "
                f"`grace run-batch --online --arms agent --sample {size} --workers 2` then "
                "`grace eval --on-sample`.", "",
                table(s["arms"], ["noop", "baseline", "agent"]).replace("| noop |", "| do nothing |")
                .replace("| baseline |", "| rules baseline |").replace("| agent |", "| **agent (Gemini)** |"), ""]
        verdict = ("does NOT beat the rules baseline on revenue preserved — it ties it"
                   if sa["rupees_preserved_paise"] == sb["rupees_preserved_paise"] else
                   "beats the rules baseline on revenue preserved" if sa["rupees_preserved_paise"] > sb["rupees_preserved_paise"]
                   else "**loses to the rules baseline on revenue preserved**")
        out += [f"**On this sample the agent {verdict}** ({fmt_inr(sa['rupees_preserved_paise'])} vs "
                f"{fmt_inr(sb['rupees_preserved_paise'])}), with {sa['interventions']} interventions to the "
                f"baseline's {sb['interventions']} and cause accuracy {pct(sa.get('cause_accuracy'))} vs "
                f"{pct(sb.get('cause_accuracy'))}.", "",
                f"- **n is small** ({size} mandates, {sa['at_risk']} at risk) — not enough to separate arms on a rupee total.",
                f"- **Served by:** {llm.get('served_by', {})} (requested `{llm.get('requested_model')}`; "
                f"{llm.get('fallbacks_used', 0)} fallback(s)). A run served by lite/fallback models is not a "
                "flagship-model result and is not presented as one.",
                f"- **Cost:** {llm.get('input_tokens', 0):,} input + {llm.get('output_tokens', 0):,} output + "
                f"{llm.get('thinking_tokens', 0):,} thinking tokens, {llm.get('mean_latency_ms', 0)/1000:.1f}s mean latency.",
                f"- Policy overrides on real model output: {sa.get('gate_flags', {})}.", ""]
    else:
        out += ["### Live model result", "",
                "_No online sample has been scored against this cohort yet. Run "
                "`grace run-batch --online --arms agent --sample 60 --workers 2`, then `grace eval --on-sample`, "
                "save the payload as `runs/demo/eval_online_sample.json`, and regenerate._", ""]
    out += ["### Integrity", "",
            "| | do nothing | rules baseline | agent |", "|---|---|---|---|",
            "| Guard blocks | " + " | ".join(str(arms[c]["batch"].get("guard_blocks", 0)) for c in ("noop", "baseline", "agent")) + " |",
            "| Double debits prevented | " + " | ".join(str(arms[c]["batch"].get("double_debits_prevented", 0)) for c in ("noop", "baseline", "agent")) + " |",
            "| **Double debits detected** | " + " | ".join(f"**{arms[c]['batch'].get('double_debits_detected', 0)}**" for c in ("noop", "baseline", "agent")) + " |", "",
            "The baseline follows the natural naive rule — *the payment failed, so charge it again* — and walks "
            "into the eMandate confirmation window; the guard blocks every one. The agent proposes it far less, "
            "because it can see `emandate_attempt_in_flight`. `grace run-batch --no-guard` shows the same batch "
            "without protection: blocked charges become real double debits. Grace never auto-refunds one; it opens "
            "a ticket and escalates.", "", "### Predictor", ""]
    if pred:
        out += [f"Brier **{pred['holdout']['brier']}** on the holdout, against **{pred.get('baseline_brier_predicting_base_rate')}** "
                f"for predicting the base rate. The pre-emptive-pause threshold ({pred.get('preemptive_threshold')}) was "
                "chosen on the **training split** by maximising counterfactual net value; the holdout was never consulted.", ""]
    out += [END]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="demo")
    args = ap.parse_args()
    readme = Path("README.md")
    txt = readme.read_text()
    block = build(Path("runs") / args.run)
    if BEGIN in txt and END in txt:
        i, j = txt.index(BEGIN), txt.index(END) + len(END)
        txt = txt[:i] + block + txt[j:]
    else:
        i = txt.index("## Results\n") + len("## Results\n")
        j = txt.index("---\n\n## Honesty")
        txt = txt[:i] + "\n" + block + "\n\n" + txt[j:]
    readme.write_text(txt)
    print("README results section regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
